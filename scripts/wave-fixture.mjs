// Writes shared/wave-fixture.json: the reference output of the waveform math in shared/CONTRACT.md.
// Both libraries test their implementation against this file. Run: node scripts/wave-fixture.mjs
import fs from 'node:fs';

const root = new URL('..', import.meta.url);
const tok = JSON.parse(fs.readFileSync(new URL('shared/design-tokens.json', root), 'utf8')).wave;

const fmt = (v) => {
  const s = (Math.round(v * 100) / 100).toFixed(2);
  return s === '-0.00' ? '0.00' : s;
};

function strandPath(i, t, level) {
  const s = tok.strands[i];
  const W = tok.viewBoxWidth;
  const H = tok.viewBoxHeight;
  const A = tok.idleAmp + (1 - tok.idleAmp) * level;
  const parts = [];
  for (let k = 0; k < tok.points; k++) {
    const x = k / (tok.points - 1);
    const env = Math.sin(Math.PI * x) ** 2;
    const y =
      H / 2 + (H / 2 - tok.strokePad) * env * s.amp * A * Math.sin(2 * Math.PI * s.freq * x + s.phase + s.speed * t);
    parts.push(`${k === 0 ? 'M' : 'L'}${fmt(x * W)} ${fmt(y)}`);
  }
  return parts.join(' ');
}

const cases = [0, 1, 2].map((i) => ({ strand: i, t: 0.5, level: 0.5, state: 'listening', d: strandPath(i, 0.5, 0.5) }));
const out = {
  $comment:
    "GENERATED by scripts/wave-fixture.mjs — do not edit by hand. Expected SVG paths for the waveform math in CONTRACT.md. Tokens are 'M' or 'L', then x, a space, y, joined by single spaces. Every number is round(v * 100) / 100 with exactly 2 decimals; -0.00 is written as 0.00. No value in these cases sits on an exact rounding tie, so JS Math.round and Rust f64::round agree.",
  cases,
};
fs.writeFileSync(new URL('shared/wave-fixture.json', root), JSON.stringify(out, null, 2) + '\n');
console.log(cases[0].d);
